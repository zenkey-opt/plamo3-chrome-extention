// Vendor wllama (llama.cpp compiled to WebAssembly + WebGPU) into extension/vendor/wllama.
//
// Why a patch is needed: MV3 extension pages may only run scripts from the extension
// itself ('self'), so wllama's runtime-assembled blob: worker is blocked. This script
// writes that worker code to a static file (llama-worker.js) and patches
// ProxyToWorker.moduleInit to load it, passing RUN_OPTIONS through the URL hash.
//
// usage: node tools/vendor-wllama.mjs [srcBase] [--wasm-dir DIR]
//   srcBase:    a wllama build tree containing esm/index.js and esm/wasm/wllama.wasm
//               (default: https://github.ngxson.com/wllama = CI build of wllama master)
//   --wasm-dir: take wllama.js (emscripten glue) + wllama.wasm from a local build instead
//               (tools/build-wllama.sh output, same wllama commit as srcBase); BUILD.json there
//               is recorded in VERSION.json
//   --reuse-index: with --wasm-dir, keep the vendored (already patched) index.js and only regenerate
//               llama-worker.js (glue) + wllama.wasm from the local build, so glue and wasm always match.
//               EXT_DIR=<dir relative to the repo> targets another copy (e.g. .work/ext-test).
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync, readFileSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, process.env.EXT_DIR || 'extension', 'vendor', 'wllama');
const argv = process.argv.slice(2);
const wi = argv.indexOf('--wasm-dir');
const WASM_DIR = wi >= 0 ? argv.splice(wi, 2)[1] : null;
const ri = argv.indexOf('--reuse-index');
const REUSE = ri >= 0 && argv.splice(ri, 1).length > 0;
if (REUSE && !WASM_DIR) throw new Error('--reuse-index needs --wasm-dir');
const MV3_MARK = '/* patched for MV3: no blob: workers */';
const SRC = (argv[0] || 'https://github.ngxson.com/wllama').replace(/\/$/, '');

async function get(path) {
  if (/^https?:/.test(SRC)) {
    const r = await fetch(`${SRC}/${path}`, { cache: 'no-store' });
    if (!r.ok) throw new Error(`${SRC}/${path}: HTTP ${r.status}`);
    return { buf: Buffer.from(await r.arrayBuffer()), modified: r.headers.get('last-modified') };
  }
  return { buf: readFileSync(join(SRC, path)), modified: null };
}
const sha256 = (b) => createHash('sha256').update(b).digest('hex');

const js = REUSE ? { buf: readFileSync(join(OUT, 'index.js')), modified: null } : await get('esm/index.js');
if (REUSE && !js.buf.toString('utf8').includes(MV3_MARK)) throw new Error(`${OUT}/index.js is not a vendored (patched) index.js`);
const wasm = WASM_DIR ? { buf: readFileSync(join(WASM_DIR, 'wllama.wasm')), modified: null } : await get('esm/wasm/wllama.wasm');
const build = WASM_DIR ? JSON.parse(readFileSync(join(WASM_DIR, 'BUILD.json'), 'utf8')) : null;
let src = js.buf.toString('utf8');

// 1) Pull the generated worker sources out of the bundle by re-exporting them.
mkdirSync(OUT, { recursive: true });
const tmp = join(OUT, '.extract.mjs');
writeFileSync(
  tmp,
  src +
    '\nexport { JSPI_STUB as __JSPI, WLLAMA_EMSCRIPTEN_CODE as __EMS, LLAMA_CPP_WORKER_CODE as __WORKER, LIBLLAMA_VERSION as __LIBLLAMA };\n'
);
let g;
try {
  g = { ...(await import(pathToFileURL(tmp).href)) }; // plain copy: module namespaces are read-only
} finally {
  rmSync(tmp, { force: true });
}
for (const k of ['__JSPI', '__EMS', '__WORKER', '__LIBLLAMA']) {
  if (typeof g[k] !== 'string' || !g[k]) throw new Error(`could not extract ${k}`);
}
if (WASM_DIR) {
  const ciEms = g.__EMS;
  g.__EMS = readFileSync(join(WASM_DIR, 'wllama.js'), 'utf8');
  // the glue must at least export the same entry points the worker code calls
  for (const f of ['_wllama_start', '_wllama_action', '_wllama_exit']) {
    if (ciEms.includes(f) && !g.__EMS.includes(f)) throw new Error(`local wllama.js lacks ${f}`);
  }
}
if (!g.__EMS.includes('var Module')) throw new Error('emscripten code layout changed (no "var Module")');

// 2) Static worker = exactly what ProxyToWorker.moduleInit would have put in the blob.
const worker = [
  `// Generated by tools/vendor-wllama.mjs from wllama (libllama ${g.__LIBLLAMA})${build ? ` + local wasm build (${build.patches.join(', ')})` : ''}. Do not edit.`,
  'const RUN_OPTIONS = JSON.parse(decodeURIComponent(self.location.hash.slice(1)));',
  'function wModuleInit() {',
  'if (RUN_OPTIONS.noWebGPU) { try{Object.defineProperty(WorkerNavigator.prototype,"gpu",{get:()=>({requestAdapter:async()=>null})});}catch(e){} }',
  (g.__JSPI + g.__EMS).replace('var Module', 'var ___Module') + ';',
  'return Module; }',
  g.__WORKER,
].join('\n\n');

if (REUSE) {
  writeFileSync(join(OUT, 'llama-worker.js'), worker);
  writeFileSync(join(OUT, 'wllama.wasm'), wasm.buf);
  const meta = JSON.parse(readFileSync(join(OUT, 'VERSION.json'), 'utf8'));
  meta.wasmBuild = build;
  meta.sha256['wllama.wasm'] = sha256(wasm.buf);
  meta.sha256['wllama.js(local build)'] = sha256(Buffer.from(g.__EMS));
  writeFileSync(join(OUT, 'VERSION.json'), JSON.stringify(meta, null, 2) + '\n');
  console.log(JSON.stringify({ ...meta, out: OUT, workerBytes: worker.length, wasmBytes: wasm.buf.length }, null, 2));
  process.exit(0);
}

// 3) Patch the single blob-worker creation used for inference.
const needle = 'this.worker = createWorker(completeCode);';
const count = src.split(needle).length - 1;
if (count !== 1) throw new Error(`expected 1 occurrence of moduleInit worker creation, found ${count}`);
src = src.replace(
  needle,
  'this.worker = new Worker(new URL("./llama-worker.js", import.meta.url).href + "#" + ' +
    'encodeURIComponent(JSON.stringify(Object.assign({}, runOptions, { noWebGPU: !!this.resources.noWebGPU }))), ' +
    '{ type: "module" }); ' + MV3_MARK
);
src = `// wllama (MIT, https://github.com/ngxson/wllama) — vendored by tools/vendor-wllama.mjs; libllama ${g.__LIBLLAMA}\n` + src;

writeFileSync(join(OUT, 'index.js'), src);
writeFileSync(join(OUT, 'llama-worker.js'), worker);
writeFileSync(join(OUT, 'wllama.wasm'), wasm.buf);
// licences of the vendored code (both MIT)
for (const [name, url] of [
  ['LICENSE-wllama', 'https://raw.githubusercontent.com/ngxson/wllama/master/LICENCE'],
  ['LICENSE-llama.cpp', 'https://raw.githubusercontent.com/ggml-org/llama.cpp/master/LICENSE'],
]) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`${url}: HTTP ${r.status}`);
  writeFileSync(join(OUT, name), Buffer.from(await r.arrayBuffer()));
}
const meta = {
  source: SRC,
  sourceModified: js.modified || wasm.modified,
  libllama: g.__LIBLLAMA,
  ...(build ? { wasmBuild: build } : {}),
  vendoredAt: new Date().toISOString(),
  sha256: {
    'index.js(original)': sha256(js.buf),
    'wllama.wasm': sha256(wasm.buf),
    ...(build ? { 'wllama.js(local build)': sha256(Buffer.from(g.__EMS)) } : {}),
  },
};
writeFileSync(join(OUT, 'VERSION.json'), JSON.stringify(meta, null, 2) + '\n');
console.log(JSON.stringify({ ...meta, out: OUT, workerBytes: worker.length, indexBytes: src.length, wasmBytes: wasm.buf.length }, null, 2));
